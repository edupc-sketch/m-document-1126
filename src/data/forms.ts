export type FormCategory =
  | '산지전용'
  | '산지일시사용'
  | '토석채취'
  | '입목벌채'
  | '기타';

export interface FormFileItem {
  /** 파일 형식 ('PDF' 또는 'HWP') */
  format: 'PDF' | 'HWP';
  /** public/forms/ 폴더 기준 경로 (예: '/forms/sanji-ilsi-7-2.pdf') */
  url: string;
  /** 민원인이 내려받을 때 저장되는 한글 파일명 (확장자 포함) */
  downloadName: string;
}

export interface DocumentGroup {
  /** 신청 유형 구분 (예: '허가', '변경허가', '기간연장') */
  type: string;
  /** 해당 신청 유형의 제출서류 목록 */
  items: string[];
}

export interface ForestryForm {
  /** 고유 식별자 (겹치지 않는 영문/숫자 아이디) */
  id: string;
  /** 분류: '산지전용' | '산지일시사용' | '토석채취' | '입목벌채' | '기타' */
  category: FormCategory;
  /** 근거 법령 및 서식번호 */
  legalBasis: string;
  /** 서식명 */
  title: string;
  /** 개정일 (예: '2026. 8. 27.') */
  revisedDate: string;
  /** 처리기간 */
  processingPeriod: string;
  /** 수수료 */
  fee: string;
  /** 첨부파일 목록 (PDF와 HWP를 모두 넣으면 버튼이 각각 표시됩니다) */
  files: FormFileItem[];
  /** 신청 유형별 제출서류 목록 */
  requiredDocuments: DocumentGroup[];
  /** 처리절차 (앞에서부터 순서대로 화살표로 연결되어 표시됩니다) */
  processSteps: string[];
}

